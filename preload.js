const { contextBridge, ipcRenderer, webUtils } = require('electron');

const invoke = (ch, ...args) => ipcRenderer.invoke(ch, ...args);

contextBridge.exposeInMainWorld('api', {
  home: ipcRenderer.sendSync('sys:home'),
  list: (dir) => invoke('fs:list', dir),
  stat: (p) => invoke('fs:stat', p),
  dirSize: (p) => invoke('fs:dirSize', p),
  props: (p) => invoke('fs:props', p),
  conflicts: (sources, destDir) => invoke('fs:conflicts', sources, destDir),
  transfer: (opts) => invoke('fs:transfer', opts),
  undoMove: (pairs) => invoke('fs:undoMove', pairs),
  rename: (p, name) => invoke('fs:rename', p, name),
  mkdir: (dir, name) => invoke('fs:mkdir', dir, name),
  newFile: (dir, name) => invoke('fs:newFile', dir, name),
  trash: (paths) => invoke('fs:trash', paths),
  remove: (paths) => invoke('fs:delete', paths),
  open: (p) => invoke('fs:open', p),
  reveal: (p) => invoke('fs:reveal', p),
  terminal: (dir) => invoke('fs:terminal', dir),
  preview: (p) => invoke('fs:preview', p),
  places: () => invoke('sys:places'),
  watch: (dirs) => ipcRenderer.send('fs:watch', dirs),
  onChanged: (fn) => ipcRenderer.on('fs:changed', (_, dir) => fn(dir)),
  onProgress: (fn) => ipcRenderer.on('op:progress', (_, d) => fn(d)),
  copyText: (t) => invoke('clip:writeText', t),
  writeFilesClipboard: (mode, paths) => invoke('clip:writeFiles', mode, paths),
  readFilesClipboard: () => invoke('clip:readFiles'),
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  batchRename: (pairs) => invoke('fs:batchRename', pairs),
  opControl: (id, action) => ipcRenderer.send('op:control', id, action),
  link: (sources, destDir, kind) => invoke('fs:link', sources, destDir, kind),
  exif: (p) => invoke('fs:exif', p),
  templates: () => invoke('tpl:list'),
  fromTemplate: (tpl, destDir) => invoke('tpl:create', tpl, destDir),
  saveTemplate: (p) => invoke('tpl:save', p),
  apps: (p) => invoke('sys:apps', p),
  openMap: (lat, lon) => invoke('sys:openMap', lat, lon),
  openWith: (file, app, mime, makeDefault) => invoke('sys:openWith', file, app, mime, makeDefault),
  newWindow: (query) => ipcRenderer.send('win:new', query),
  onOpenPath: (fn) => ipcRenderer.on('app:open', (_, p) => fn(p)),
  setBackground: (on) => invoke('app:background', on),
  setHotkey: (accel) => invoke('app:hotkey', accel),
  defaultFM: (set) => invoke('sys:defaultFM', set),
  scripts: () => invoke('scripts:list'),
  runScript: (opts) => invoke('scripts:run', opts),
  runProgram: (file, args, admin) => invoke('sys:run', file, args, admin),
  splitArgs: (line) => invoke('sys:splitArgs', line),
  net: {
    mounts: () => invoke('net:mounts'),
    connect: (opts) => invoke('net:connect', opts),
    unmount: (p) => invoke('net:unmount', p),
    shares: (host) => invoke('net:shares', host),
    scan: () => invoke('net:scan'),
  },
  officePreview: (p) => invoke('pv:office', p),
  mailPreview: (p) => invoke('pv:eml', p),
  outlookPreview: (p) => invoke('pv:msg', p),
  thumb: (p) => invoke('thumb:get', p),
  putThumb: (key, bytes) => invoke('thumb:put', key, bytes),
  thumbStats: (clear) => invoke('thumb:stats', clear),
  videoThumb: (p) => invoke('thumb:video', p),
  pickImage: () => invoke('dialog:pickImage'),
  writeNew: (dir, name, bytes) => invoke('fs:writeNew', dir, name, bytes),
  mediaMeta: (paths) => invoke('fs:mediaMeta', paths),
  probe: (p) => invoke('fs:probe', p),
  iconThemes: () => invoke('icons:themes'),
  resolveIcons: (theme, names) => invoke('icons:resolve', theme, names),
  readText: () => invoke('clip:readText'),
  tags: () => invoke('tags:get'),
  setTag: (paths, color) => invoke('tags:set', paths, color),
  onTags: (fn) => ipcRenderer.on('tags:changed', (_, t) => fn(t)),
  archive: {
    extract: (opts) => invoke('arc:extract', opts),
    compress: (opts) => invoke('arc:compress', opts),
    list: (p, password) => invoke('arc:list', p, password),
    cancel: (id) => ipcRenderer.send('arc:cancel', id),
    onProgress: (fn) => ipcRenderer.on('arc:progress', (_, d) => fn(d)),
  },
  search: {
    start: (id, opts) => invoke('search:start', id, opts),
    cancel: (id) => ipcRenderer.send('search:cancel', id),
    onBatch: (fn) => ipcRenderer.on('search:batch', (_, d) => fn(d)),
  },
  win: {
    min: () => ipcRenderer.send('win:min'),
    max: () => ipcRenderer.send('win:max'),
    close: () => ipcRenderer.send('win:close'),
    isMax: () => invoke('win:isMax'),
    onState: (fn) => ipcRenderer.on('win:state', (_, m) => fn(m)),
  },
});
